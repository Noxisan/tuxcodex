"""Write the CSS for the area separators in the sidebar.

Material numbers the sidebar entries (#__nav_1, #__nav_2, ...) in the order of `nav`, so the
IDs change whenever a chapter is inserted before them. This script reads the built site,
finds the first chapter of every area and rewrites the block between the markers in
docs/stylesheets/tuxdex.css.

Run after changing the order of `nav`:
    mkdocs build && python3 scripts/sidebar_separators.py && mkdocs build --strict
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS = ROOT / "docs/stylesheets/tuxdex.css"
START, END = "/* sidebar-separators:start */", "/* sidebar-separators:end */"

# First chapter of every area (English nav title) and the caption in both languages
AREAS = [
    ("Orientation", "Linux administration", "Linux-Administration"),
    ("Web servers", "Server services", "Serverdienste"),
    ("Bash scripting", "Automation & DevOps", "Automatisierung & DevOps"),
    ("Security scanning", "Security", "Sicherheit"),
]

html = (ROOT / "site/index.html").read_text()
ids = {}
for m in re.finditer(r'id="(__nav_\d+)"', html):
    start = html.find("md-ellipsis", m.end())
    title = re.sub(r"\s+", " ", html[start + 13:start + 60]).split("<")[0].strip()
    ids.setdefault(title, m.group(1))

sel = [f".md-nav--primary #{ids[first]} + .md-nav__link" for first, _, _ in AREAS]
css = [START,
       "/* Generated by scripts/sidebar_separators.py: a line with a caption above the first",
       "   chapter of every area. The rule targets the link right after the toggle, so it works",
       "   without :has() in every browser. */",
       ",\n".join(sel) + " {",
       "  flex-wrap: wrap;", "  margin-top: 0.9rem;", "  padding-top: 0.9rem;",
       "  border-top: 1px solid var(--tc-border);", "}", "",
       ",\n".join(s + "::before" for s in sel) + " {",
       "  display: block;", "  flex: 0 0 100%;", "  margin: 0 0 0.4rem;", "  font-size: 0.6rem;",
       "  font-weight: 700;", "  letter-spacing: 0.06em;", "  text-transform: uppercase;",
       "  color: var(--tc-muted);", "}", ""]
for s, (_, en, de) in zip(sel, AREAS):
    css += [f"{s}::before {{", f'  content: "{en}";', "}", "",
            f'html[lang="de"] {s}::before {{', f'  content: "{de}";', "}", ""]
css.append(END)

text = CSS.read_text()
text = text[:text.index(START)] + "\n".join(css) + text[text.index(END) + len(END):]
CSS.write_text(text)
print({first: ids[first] for first, _, _ in AREAS})
